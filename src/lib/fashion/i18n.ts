export type FashionDictionary = (typeof fashionI18n)[FashionLocale];

export function advertiseKindLabel(
  kind: string | undefined,
  fc: FashionDictionary,
): string {
  switch (kind) {
    case "new":
      return fc.admin.newProduct;
    case "discount":
      return fc.admin.discount;
    case "offer":
      return fc.admin.offer;
    case "custom":
      return fc.admin.custom;
    default:
      return fc.admin.offer;
  }
}
